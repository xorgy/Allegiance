#!/usr/bin/env python3
"""Report native IGC callback coverage from the actual interface and adapter sources.

Presence is not equivalence. Keep the behavioral verdicts in native-equivalence.md.
Run from any directory; no game data or build is needed.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
igc = (root / 'src/Igc/igc.h').read_text(encoding='latin1')
native = (root / 'src/native/game.cpp').read_text()

def body(text, declaration):
    start = text.index('{', text.index(declaration))
    level, end = 1, start + 1
    while level:
        if text[end] == '{': level += 1
        elif text[end] == '}': level -= 1
        end += 1
    return text[start + 1:end - 1]

print('# Native IGC callback inventory\n')
print('Generated by `python src/native/audit_callbacks.py`. An override only establishes\n'
      'that a callback is wired; it does **not** establish equivalent behavior. See\n'
      '[the audit and work queue](native-equivalence.md) for semantic findings.\n')
print('Tables list declared callback names (overloads grouped). The shared AttachSite\n'
      'base is listed separately for both adapters. Defaults are reported from source;\n'
      'a default may be intentional, but still needs a semantic disposition.\n')
# Dispositions cover inherited responsibilities, rather than adding dummy
# overrides to inflate coverage. Sources are the original adapters/callers.
dispositions = {
    'IIgcSite': {
        'ChangeGameState': 'Local state is read from IGC and lifecycle callbacks; transport game-state event deferred (Q13)',
        'ClientTimeFromServerTime': 'Identity is correct for local authority; clock synchronization deferred (Q13)',
        'ServerTimeFromClientTime': 'Identity is correct for local authority; clock synchronization deferred (Q13)',
        'ClusterUpdateEvent': 'Original FedSrv callback is empty; no local responsibility',
        'CreateSideEvent': 'FedSrv allocates its CFSSide wrapper; native setup owns local side state directly',
        'DestroySideEvent': 'FedSrv deletes its CFSSide wrapper; native mission teardown owns side lifetime',
        'DrainAsteroidEvent': 'MineOre caller is commented out in the original; inactive',
        'MineAsteroidEvent': 'Original IGC changes ore locally; FedSrv callback replicates it (Q13)',
        'GetDroneFromShip': 'Opaque CFSDrone wrapper lookup; no native IGC caller or server wrapper',
        'GetCluster': 'Original offline CanSee predicate retained; remote last-seen status deferred (Q13)',
        'GetRipcordCluster': 'Live offline ships use original default; replicated historical ship status deferred (Q13)',
        'EjectPlayer': 'Native KillShipEvent applies shared pod/death/camera behavior; separate transport event deferred (Q13)',
        'ShipWarped': 'Native HitWarpEvent applies shared transit and ChangeCluster updates presentation; packet event deferred (Q13)',
        'TargetKilled': 'Native TerminateModelEvent calls shared TargetKilled; no second invocation needed',
        'MessageBox': 'Original debug/platform dialog; runtime failures use native exceptions and frontend errors',
    },
    'ThingSite': {
        'ActivateBolt': 'Mining lightning reads the original IGC mining state; no retained bolt object',
        'DeactivateBolt': 'Mining lightning reads the original IGC mining state; no retained bolt object',
        'AddMuzzleFlare': 'Disabled by the original WinTrek guard; intentionally absent',
        'GetChildOffset': 'Legacy render-space helper; IGC uses implemented GetChildModelOffset',
        'SetPosition': 'Native scene/effects pull original IGC transform; no second retained transform',
        'SetOrientation': 'Native scene/effects pull original IGC transform; no second retained transform',
        'SetVisible': 'Legacy cockpit render selector; native visibility and camera showPlayer replace it',
        'SetTexture': 'No active IGC caller in supported sources; load callbacks preserve authored textures',
        'Purge': 'Legacy retained render resources; native cache ownership replaces it',
        'GetGeo': 'Legacy renderer pointer intentionally absent',
        'GetThingGeo': 'Legacy renderer pointer intentionally absent',
        **{name: 'Legacy radar scratch state; native radar computes the shared policy in HUD batches'
           for name in ('GetMask','SetMask','OrMask','AndMask','XorMask','GetScreenPosition','GetScreenRadius','GetDistanceToEdge','GetRadarState')},
    },
    'ClusterSite': {
        'GetRotation': 'Legacy sector-map UI rotation; no IGC simulation caller',
        'AddRotation': 'Legacy sector-map UI rotation; no IGC simulation caller',
        'MoveShip': 'Legacy asset-mask invalidation; native existing snapshot traversal folds shared asset masks',
        'MoveStation': 'Legacy asset-mask invalidation; native existing snapshot traversal folds shared asset masks',
        'GetScreenPosition': 'Native sector map projects its authored 2D location directly',
        **{name: 'Legacy render pointer intentionally absent; native sector background batches preserve authored skies/posters'
           for name in ('GetEnvironmentGeo','GetGroupScene','GetPosterImage')},
    },
    'AttachSite': {
        'AddPulse': 'Sector pulse rendering is disabled in original ClusterSiteImpl',
        'AddThingSite': 'Legacy retained scene membership; native Thing constructor registers in its own scene set',
        'DeleteThingSite': 'Legacy retained scene membership; native Thing destructor removes scene membership',
        'Terminate': 'No legacy AttachSite-owned resources; native destructors/Thing override own their lifetimes',
        'AddExplosion': 'Native adapters route original local-offset and sector explosion events to preloaded particle/sound batches',
    },
}
for interface, adapter in [('IIgcSite', 'struct Game::Impl'), ('ThingSite', 'struct Thing :'), ('ClusterSite', 'struct SectorSite :'),
                           ('AttachSite', 'struct Thing :'), ('AttachSite', 'struct SectorSite :')]:
    declarations = body(igc, 'class ' + interface + ' :')
    implementations = body(native, adapter)
    methods = sorted(set(re.findall(r'virtual\s+[^;{}]*?\b(\w+)\s*\(', declarations)) - {interface})
    overrides = set(re.findall(r'\b(\w+)\s*\([^;{}]*\)\s*(?:const\s*)?override', implementations))
    present = [m for m in methods if m in overrides]
    suffix = (' / ' + ('Thing' if adapter == 'struct Thing :' else 'SectorSite')) if interface == 'AttachSite' else ''
    print(f'## {interface}{suffix}: {len(present)} / {len(methods)} names overridden\n')
    print('| Callback | Original default | Native adapter |\n|---|---|---|')
    for method in methods:
        defaults = []
        for match in re.finditer(r'\b' + re.escape(method) + r'\s*\([^{};]*\)[^{;]*\{', declarations):
            implementation = body(declarations[match.start():], method)
            returned = re.search(r'\breturn\s+([^;]+);', implementation)
            default = '`return ' + ' '.join(returned[1].split()) + '`' if returned else 'No action'
            if default not in defaults: defaults.append(default)
        verdict = 'Override; audit semantics' if method in overrides else dispositions.get(interface, {}).get(method, 'Inherited default; review required')
        print(f'| `{method}` | {" / ".join(defaults)} | {verdict} |')
    print()
